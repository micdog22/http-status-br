export function refUrl(ref) {
  return `https://www.rfc-editor.org/rfc/rfc${ref.rfc}${ref.section ? `#section-${ref.section}` : ''}`;
}

export function refLabel(ref) {
  return `RFC ${ref.rfc}${ref.section ? `, seção ${ref.section}` : ''}`;
}
